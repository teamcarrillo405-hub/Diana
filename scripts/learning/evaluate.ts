import { mkdir,readFile,writeFile } from "node:fs/promises";
import path from "node:path";
import { createClient } from "@supabase/supabase-js";
import { highSchoolLearningCorpus } from "../../lib/learning-engine/evaluation-corpus";
import { corpusDigest,experimentInput,experimentManifestSchema,summarizeExperiment,validateEvaluationCorpus,EXPERIMENT_ARMS,type ExperimentOutput } from "../../lib/learning-engine/experiments";
import {evaluationContext,scoreEngineeringOutputs} from "../../lib/learning-engine/evaluation-pipeline";
import {sha256} from "../../lib/learning-engine/curriculum";

async function main() {
  const command=process.argv[2]??"validate";
  const directory=path.resolve(process.argv[3]??"artifacts/learning-engine");
  const corpus=highSchoolLearningCorpus();
  const errors=validateEvaluationCorpus(corpus);
  if(errors.length) throw new Error(errors.join("\n"));
  if(command==="approve-fixtures"){
    const corpusHash=await corpusDigest(corpus);
    const hashes:Record<string,string>={};
    for(const item of corpus){
      const context=await evaluationContext(item);
      for(const arm of EXPERIMENT_ARMS){
        const manifest=experimentManifestSchema.parse({id:crypto.randomUUID(),version:"high-school-learning-v1",corpusHash,
          codeRevision:"fixture-generation",model:"configured-at-runtime",promptVersion:"v1",arm,split:"test",maxOutputTokens:1000,
          maxInputBytes:32000,maxBatchCents:1000,monthlyCapCents:10000,humanReview:"pending"});
        hashes[item.id+":"+arm]=await sha256(experimentInput(item,manifest,context));
      }
    }
    await writeFile(path.resolve("supabase/functions/_shared/learning/approved-fixtures.ts"),
      "// Generated by learning:evaluate approve-fixtures. Authored synthetic inputs only.\n"
      +"export const approvedCorpusHash="+JSON.stringify(corpusHash)+";\n"
      +"export const approvedInputHashes:Record<string,string>="+JSON.stringify(hashes,null,2)+";\n");
    console.log("Pinned "+Object.keys(hashes).length+" authored fixture inputs. No provider call made.");return;
  }
  if(command==="validate") {
    console.log(JSON.stringify({cases:corpus.length,corpusHash:await corpusDigest(corpus),provenance:"authored_engineering_fixtures",
      completedProviderRuns:0,humanReview:"pending",mediaRecognitionCoverage:"not_established"},null,2)); return;
  }
  if(command==="fixtures") {
    await mkdir(directory,{recursive:true});
    await writeFile(path.join(directory,"high-school-learning-v1.jsonl"),corpus.map(item=>JSON.stringify(item)).join("\n")+"\n");
    await writeFile(path.join(directory,"corpus-manifest.json"),JSON.stringify({hash:await corpusDigest(corpus),count:corpus.length,
      generatedFrom:"lib/learning-engine/evaluation-corpus.ts",humanReviewed:false,qualification:"engineering_seed_not_research_evidence"},null,2)+"\n");
    console.log("Wrote 480 authored engineering fixtures. No provider evaluation was run."); return;
  }
  if(command!=="run") throw new Error("Use validate, fixtures or run.");
  const manifest=experimentManifestSchema.parse(JSON.parse(await readFile(path.join(directory,"experiment.json"),"utf8")));
  if(manifest.corpusHash!==await corpusDigest(corpus)) throw new Error("Corpus hash does not match this experiment.");
  const url=process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key=process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY;
  const token=process.env.DIANA_EVALUATION_ACCESS_TOKEN;
  if(!url || !key || !token) throw new Error("Set the Supabase URL, public key and an authorized operator access token.");
  const client=createClient(url,key,{global:{headers:{Authorization:"Bearer "+token}},auth:{persistSession:false,autoRefreshToken:false}});
  const outputPath=path.join(directory,"outputs.jsonl");
  const saved=await readFile(outputPath,"utf8").catch(()=>"");
  const outputs:ExperimentOutput[]=saved.trim()?saved.trim().split("\n").map(line=>JSON.parse(line) as ExperimentOutput):[];
  const existing=summarizeExperiment(corpus,outputs,manifest);
  if(existing.errors.length) throw new Error(existing.errors.join("\n"));
  const done=new Set(outputs.map(output=>output.caseId));
  // A durable request plan survives interruption before an output reaches disk.
  const requestPath=path.join(directory,"requests.json");
  let requests:Record<string,{requestId:string;batchId:string}>;
  try {requests=JSON.parse(await readFile(requestPath,"utf8"));} catch {
    const batches=Array.from({length:Math.ceil(corpus.length/25)},()=>crypto.randomUUID());
    requests=Object.fromEntries(corpus.map((item,index)=>[item.id,{requestId:crypto.randomUUID(),batchId:batches[Math.floor(index/25)]}]));
    await writeFile(requestPath,JSON.stringify(requests,null,2)+"\n");
  }
  let batchCents=0;
  const executedContexts:Record<string,unknown>={};
  const remaining=corpus.filter(item=>item.split==="test"&&!done.has(item.id));
  const nextBatch=remaining[0]?requests[remaining[0].id]?.batchId:null;
  if(remaining.length&&!nextBatch)throw new Error("The durable request plan is incomplete. Restore it before resuming.");
  // One bounded batch per invocation. A later invocation advances to the next
  // saved batch, while uncertain requests retain their exact original IDs.
  for(const item of remaining.filter(item=>requests[item.id]?.batchId===nextBatch)) {
    const context=await evaluationContext(item);
    executedContexts[item.id]=context;
    await writeFile(path.join(directory,"contexts-latest-batch.json"),JSON.stringify(executedContexts,null,2)+"\n");
    const response=await client.functions.invoke("learning-experiment",{body:{
      ...requests[item.id],caseId:item.id,manifest,input:experimentInput(item,manifest,context),
    }});
    if(response.error || !response.data?.ok) {
      console.log("Evaluation paused. Review the saved request IDs and budget before resuming."); break;
    }
    const output=response.data.result as ExperimentOutput;
    const check=summarizeExperiment(corpus,[...outputs,output],manifest);
    if(check.errors.length) throw new Error(check.errors.join("\n"));
    outputs.push(output); batchCents+=output.actualCents;
    await writeFile(outputPath,outputs.map(result=>JSON.stringify(result)).join("\n")+"\n");
    if(batchCents>=manifest.maxBatchCents) break;
  }
  const summary=summarizeExperiment(corpus,outputs,manifest);
  await writeFile(path.join(directory,"summary.json"),JSON.stringify(summary,null,2)+"\n");
  await writeFile(path.join(directory,"engineering-scores.json"),JSON.stringify(scoreEngineeringOutputs(corpus,outputs),null,2)+"\n");
  console.log(JSON.stringify(summary,null,2));
}
main().catch(error=>{console.error(error instanceof Error?error.message:"Evaluation could not complete.");process.exitCode=1;});
